#!/usr/bin/env python3
"""Convert a ClockBuilder Pro register script into a C header for the MMC."""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
sections = {"preamble": [], "body": [], "postamble": []}
delay_ms = 0
section = None
for line in open(src):
    line = line.strip()
    if line.startswith("#"):
        low = line.lower()
        if "start configuration preamble" in low:
            section = "preamble"
        elif "end configuration preamble" in low:
            section = None
        elif "start configuration registers" in low:
            section = "body"
        elif "end configuration registers" in low:
            section = None
        elif "start configuration postamble" in low:
            section = "postamble"
        elif "end configuration postamble" in low:
            section = None
        m = re.search(r"delay\s+(\d+)\s*msec", low)
        if m:
            delay_ms = int(m.group(1))
        continue
    m = re.match(r"0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)", line)
    if m and section:
        sections[section].append((int(m.group(1), 16), int(m.group(2), 16)))

def array(name, regs):
    lines = ["static const si5345_reg_t %s[] = {" % name]
    for i in range(0, len(regs), 4):
        chunk = regs[i:i + 4]
        lines.append("    " + " ".join("{0x%04X, 0x%02X}," % r for r in chunk))
    lines.append("};")
    return "\n".join(lines)

hdr = []
hdr.append("/* Auto-generated by tools/gen_si5345_regs.py -- do not edit. */")
hdr.append("/* Source: %s */" % src)
hdr.append("#ifndef SI5345_REGS_H")
hdr.append("#define SI5345_REGS_H")
hdr.append("")
hdr.append("#include <stdint.h>")
hdr.append("")
hdr.append("typedef struct {")
hdr.append("    uint16_t addr;")
hdr.append("    uint8_t data;")
hdr.append("} si5345_reg_t;")
hdr.append("")
hdr.append("#define SI5345_DELAY_MS %d" % delay_ms)
for key in ("preamble", "body", "postamble"):
    hdr.append("#define SI5345_%s_LEN %d" % (key.upper(), len(sections[key])))
hdr.append("")
for key in ("preamble", "body", "postamble"):
    hdr.append(array("si5345_" + key, sections[key]))
    hdr.append("")
hdr.append("#endif /* SI5345_REGS_H */")
open(out, "w").write("\n".join(hdr) + "\n")
print("sections:", {k: len(v) for k, v in sections.items()}, "delay:", delay_ms)
